def main():
    FC_DIR.mkdir(parents=True, exist_ok=True)
    QZ_DIR.mkdir(parents=True, exist_ok=True)
    
    src_map = {}
    if SRC_MAP.exists():
        src_map = json.loads(SRC_MAP.read_text(encoding="utf-8"))
    
    for lid, d in LESSON_ASSETS.items():
        sid = d["source_id"]
        src_map[sid] = ["prenatal-1", "infant_pregnancy_foundations", lid]
    SRC_MAP.write_text(json.dumps(src_map, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {SRC_MAP} with {len(LESSON_ASSETS)} source mappings.")

    index_data = json.loads(INDEX.read_text(encoding="utf-8"))
    by_id = {l["lesson_id"]: l for l in index_data["lessons"]}

    for lid, data in LESSON_ASSETS.items():
        title = data["title"]
        sid = data["source_id"]
        cards = [{"front": f, "back": b} for f, b in data["fc"]]
        quiz = data["qz"]

        fc_id = f"gen_{lid}_fc"
        qz_id = f"gen_{lid}_qz"
        fc_rel = f"docs/lesson_assets/flashcards/{fc_id}.json"
        qz_rel = f"docs/lesson_assets/quizzes/{qz_id}.json"

        (FC_DIR / f"{fc_id}.json").write_text(
            json.dumps({"title": f"{title} — بطاقات", "cards": cards}, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8"
        )
        (QZ_DIR / f"{qz_id}.json").write_text(
            json.dumps({"title": f"{title} — اختبار", "questions": quiz}, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8"
        )

        entry = by_id.get(lid)
        if entry is not None:
            entry["source_id"] = sid
            entry["title_ar"] = title
            a = entry.setdefault("assets", {})
            a["flashcards"] = [{
                "id": fc_id,
                "file": fc_rel,
                "title": f"{title} — بطاقات",
                "item_count": len(cards),
            }]
            a["quizzes"] = [{
                "id": qz_id,
                "file": qz_rel,
                "title": f"{title} — اختبار",
                "item_count": len(quiz),
            }]

    lessons = index_data["lessons"]
    total = len(lessons)
    index_data["metadata"]["coverage"] = {
        kind: f"{sum(1 for e in lessons if (e.get('assets') or {}).get(kind))}/{total}"
        for kind in ("flashcards", "quizzes", "reports", "data_tables", "infographics", "podcasts", "videos")
    }
    INDEX.write_text(json.dumps(index_data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote flashcards + quizzes for {len(LESSON_ASSETS)} lessons and updated {INDEX}.")

if __name__ == "__main__":
    main()
