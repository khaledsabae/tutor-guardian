"""The teen QR page (backend/static/child_mode/index.html) against the API it
calls and the app it belongs to (UX_UI_ROADMAP §4.3, AUDIT H8).

It is plain HTML/JS with no build step, so nothing else checks that its
strings still match the server — which is how "partial" (the API says
"partially") shipped and failed on every tap.
"""
import re
from pathlib import Path

from app.models.value_tracking import CATEGORIES as SERVER_CATEGORIES, STATUSES

PAGE = (Path(__file__).resolve().parents[1] / "static" / "child_mode" / "index.html").read_text(
    encoding="utf-8"
)


def test_every_status_button_sends_a_status_the_api_accepts():
    sent = set(re.findall(r'data-status="([a-z_]+)"', PAGE))
    assert sent == STATUSES


def test_every_server_category_has_an_icon_and_a_label():
    for fn in ("categoryIcon", "categoryLabel"):
        body = PAGE.split(f"function {fn}(cat)", 1)[1].split("}", 2)[0]
        keys = set(re.findall(r"(\w+):", body))
        assert SERVER_CATEGORIES <= keys, (fn, keys)


def test_parent_typed_names_never_reach_markup_unescaped():
    # H8: habit names include parent-typed custom templates. Every interpolation
    # inside the card's innerHTML goes through esc(); the child's name is only
    # ever set with textContent.
    template = PAGE.split("el.innerHTML = `", 1)[1].split("`;", 1)[0]
    for expr in re.findall(r"\$\{([^}]*)\}", template):
        assert expr.strip().startswith("esc("), expr
    assert "innerHTML" not in PAGE.split("child_name", 1)[0].rsplit("\n", 1)[-1]
    assert re.search(r"textContent\s*=\s*`[^`]*\$\{data\.child_name", PAGE)


def test_missed_is_neutral_and_the_palette_is_the_apps():
    missed = re.search(r'data-status="missed" class="([^"]+)"', PAGE).group(1)
    assert "rose" not in missed and "red" not in missed
    assert "--tg-primary: #10B981" in PAGE  # AppPalette.dark.primary
    assert "family=Cairo" in PAGE


def test_every_class_the_page_uses_has_a_rule_here():
    # The page's CSS is self-hosted (styles.css), not generated by the Tailwind
    # CDN, so a class added to the markup with no rule would render unstyled.
    css = (Path(__file__).resolve().parents[1] / "static" / "child_mode" / "styles.css").read_text(
        encoding="utf-8"
    )
    inline = PAGE.split("<style>", 1)[1].split("</style>", 1)[0]
    used: set[str] = set()
    for attr in re.findall(r'class(?:Name)?\s*=\s*["\']([^"\']+)["\']', PAGE):
        used |= set(attr.split())
    used |= set(re.findall(r"classList\.(?:add|remove)\('([\w-]+)'\)", PAGE))
    missing = sorted(c for c in used if not re.search(rf"\.{re.escape(c)}[\s{{,:>]", css + inline))
    assert missing == [], f"add these to backend/static/child_mode/styles.css: {missing}"
    assert {"hidden", "flex", "shadow-lg", "opacity-50"} <= used  # the scan found the page's classes
    assert "<script src=" not in PAGE  # no third-party script on a page a child opens


def test_the_page_redeems_the_qr_url_the_backend_builds():
    # The QR is {base}/child-mode/web/?claim={code}, but init() used to redeem
    # only when the *path* contained /claim-session/ — so every fresh scan
    # landed on "امسح رمز QR" and the code was never spent.
    router = (Path(__file__).resolve().parents[1] / "app" / "routers" / "child_mode.py").read_text(
        encoding="utf-8"
    )
    built = re.search(r'claim_url = f"\{base\}(/[^"?]*)\?(\w+)=\{code\}"', router)
    assert built, "child_mode.py no longer builds the claim URL as expected"
    path, param = built.groups()
    assert path == "/child-mode/web/"

    init = PAGE.split("async function init()", 1)[1].split("\n    }\n", 1)[0]
    trigger = init.split("await claimFromUrl()", 1)[0]
    assert f"URLSearchParams(location.search).get('{param}')" in trigger
    assert "if (hasToken)" not in trigger  # a fresh scan beats a stored token
    assert "pathname" not in trigger

    claim_fn = PAGE.split("async function claimFromUrl()", 1)[1].split("\n    }\n", 1)[0]
    assert f"params.get('{param}')" in claim_fn
    assert f"/api/child-web/claim-session?{param}=" in claim_fn
    assert f"history.replaceState({{}}, '', '{path}')" in claim_fn

    # ...and the endpoint reads the code from that same query parameter.
    web = (Path(__file__).resolve().parents[1] / "app" / "routers" / "child_mode_web.py").read_text(
        encoding="utf-8"
    )
    assert re.search(rf"def claim_session\([^)]*\b{param}: str \| None = Query\(", web)
