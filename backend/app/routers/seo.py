def _faq_schema(faq: list[dict], canonical: str) -> str:
    """Render schema.org FAQPage JSON-LD."""
    if not faq:
        return ""
    data = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
            {
                "@type": "Question",
                "name": item["question"],
                "acceptedAnswer": {
                    "@type": "Answer",
                    "text": item["answer"],
                },
            }
            for item in faq
        ],
    }
    return f"""<script type="application/ld+json">{json.dumps(data, ensure_ascii=False)}</script>"""


