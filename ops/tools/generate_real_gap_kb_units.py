def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    validator = Draft202012Validator(schema)

    for u in NEW_UNITS:
        if u["text_simplified"] not in u["text_original"]:
            u["text_original"] = f"{u['text_original']} {u['text_simplified']}".strip()
        validator.validate(u)
        formatted = json.dumps(u, ensure_ascii=False, indent=2) + "\n"
        (OUT_DIR / f"{u['id']}.json").write_text(formatted, encoding="utf-8")
        (KB_UNITS_DIR / f"{u['id']}.json").write_text(formatted, encoding="utf-8")
        print(f"  [OK] Installed & validated {u['id']}.json ({u['domain']} | {u['age_group']})")

    from datetime import datetime, timezone
    from app.services.age_normalization import normalize_age_group

    units_meta = []
    for fp in sorted(KB_UNITS_DIR.glob("*.json")):
        data = json.loads(fp.read_text(encoding="utf-8"))
        raw_age = data.get("age_group", "unspecified")
        units_meta.append({
            "id": data.get("id"),
            "domain": data.get("domain"),
            "title": data.get("title", "")[:60],
            "source_file": data.get("source_file", ""),
            "language": data.get("language", ""),
            "original_age_group": raw_age,
            "normalized_age_group": normalize_age_group(raw_age),
            "behavior_type": data.get("behavior_type", ""),
            "needs_ocr": data.get("needs_ocr", False),
            "size_chars": len(data.get("text_original", "")),
        })
    by_domain: dict[str, int] = {}
    for u in units_meta:
        by_domain[u["domain"]] = by_domain.get(u["domain"], 0) + 1
    index_path = KB_UNITS_DIR.parent / "units_index.json"
    index_path.write_text(
        json.dumps(
            {
                "total_units": len(units_meta),
                "generated_at": datetime.now(timezone.utc).isoformat(),
                "by_domain": by_domain,
                "units": units_meta,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    print(f"units_index.json rebuilt: {index_path} ({len(units_meta)} units)")
    print(f"✅ Successfully installed {len(NEW_UNITS)} new KB gap units into {KB_UNITS_DIR} and updated units_index.json!")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
