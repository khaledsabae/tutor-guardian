#!/usr/bin/env python3
"""
gen_teaser_qr — the QR codes on the teaser's and the campaign reels' end cards.

Writes src/noor/qr.ts: one module path per cut, in module units, so the
end card draws it as flat SVG (dark ink modules on an ivory paper card) at
any pixel size. Error correction M, 4-module quiet zone (the card itself is
the quiet zone). No logo inside the code.

Every code points at the landing page with a campaign code, never straight
at Play: https://tg-api.alsaba.cloud/go?ref=<CODE>. The page records the scan
(referral_clicks, so ops/scripts/campaign_report.py counts it, and the AUTO
IP match can still credit the install if Play drops the referrer) and hands
Play `referrer=ref_<CODE>&utm_source=campaign_video&utm_medium=qr&
utm_campaign=<CODE>` (backend/app/services/attribution.py, prefix VD). Before
16 Oct 2026 these QR codes went straight to Play with utm only — invisible to
campaign_report.py — and the Arabic teaser's carried no utm_campaign at all.

The codes are assigned in docs/marketing/campaign_codes.md;
backend/tests/test_campaign_code_registry.py fails if this file's output and
the registry disagree.

Usage: python3 scripts/gen_teaser_qr.py
"""
from __future__ import annotations

import json
from pathlib import Path

import qrcode
from qrcode.constants import ERROR_CORRECT_M

GO = "https://tg-api.alsaba.cloud/go?ref="
# teaser cut -> campaign code (docs/marketing/campaign_codes.md)
TEASER_CODES = {
    "ar": "VD07",     # NoorTeaserAr (portrait)
    "world": "VD08",  # NoorTeaserArWorld and its voice-over cut NoorTeaserArVo
    "en": "VD09",     # NoorTeaserEn
    "wide": "VD10",   # NoorTeaserArWide
}
URLS = {cut: GO + code for cut, code in TEASER_CODES.items()}
# campaign reel slug -> code; the `_vo` cut of a reel carries the same code
CAMPAIGN_CODES = {
    "v1_remember": "VD01",
    "v2_road": "VD02",
    "v3_ask": "VD03",
    "v4_handover": "VD04",
    "v5_ramadan": "VD05",
    "v6_stories": "VD06",
}
CAMPAIGN_SLUGS = list(CAMPAIGN_CODES)
BORDER = 4
OUT = Path(__file__).resolve().parents[1] / "src" / "noor" / "qr.ts"
CAMPAIGN_OUT = Path(__file__).resolve().parents[1] / "src" / "noor" / "campaign" / "qr.ts"


def module_path(url: str) -> tuple[int, int, str]:
    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_M, border=BORDER, box_size=1)
    qr.add_data(url)
    qr.make(fit=True)
    matrix = qr.get_matrix()  # includes the quiet-zone border
    n = len(matrix)
    parts = []
    for y, row in enumerate(matrix):
        x = 0
        while x < n:
            if row[x]:
                start = x
                while x < n and row[x]:
                    x += 1
                parts.append(f"M{start} {y}h{x - start}v1h{start - x}z")
            else:
                x += 1
    return qr.version, n, "".join(parts)


def main() -> int:
    lines = [
        "// Generated by scripts/gen_teaser_qr.py — do not edit by hand.",
        "// Module paths (dark modules) in module units; n includes the 4-module quiet zone.",
        "export type QrCut = " + " | ".join(f"'{c}'" for c in URLS) + ";",
        "export const QR: Record<QrCut, {url: string; version: number; n: number; d: string}> = {",
    ]
    for key, url in URLS.items():
        version, n, d = module_path(url)
        print(f"{key:5s} version {version}  {n}x{n} modules (with border)  {len(url)} chars")
        lines.append(f"\t{key}: {{url: {json.dumps(url)}, version: {version}, n: {n}, d: {json.dumps(d)}}},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [
        "// Generated by scripts/gen_teaser_qr.py — do not edit by hand.",
        "// One Play QR per campaign reel; module paths in module units, n includes the 4-module quiet zone.",
        "export type Slug = " + " | ".join(f"'{s}'" for s in CAMPAIGN_SLUGS) + ";",
        "export const QR: Record<Slug, {url: string; version: number; n: number; d: string}> = {",
    ]
    for slug in CAMPAIGN_SLUGS:
        url = GO + CAMPAIGN_CODES[slug]
        version, n, d = module_path(url)
        print(f"{slug:12s} version {version}  {n}x{n} modules (with border)  {len(url)} chars")
        lines.append(f"\t{slug}: {{url: {json.dumps(url)}, version: {version}, n: {n}, d: {json.dumps(d)}}},")
    lines.append("};")
    CAMPAIGN_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
