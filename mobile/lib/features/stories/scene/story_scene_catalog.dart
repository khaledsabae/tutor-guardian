/// Which paper pieces make which page of which story.
///
/// One entry per page of the story, in order, read straight off the page's
/// text (who is there, where, holding what). A story the catalogue does not
/// know — a new one the server adds before the app catches up — gets a quiet
/// night-sky scene for every page rather than an empty frame or an emoji.
///
/// Placement is physical (x 0 = left), the same picture in Arabic and English.
/// People share one size (.8) so a child is always smaller than a parent.
///
/// A piece's `cue` is the words that name it, Arabic and English in one list
/// (scene_cues.dart): the narrator saying one makes it hop; `enters` keeps
/// it off the page, while the narrator reads, until it is named. A person's
/// `face` is what the page's text says they feel; `faceTo` + `faceCue` turn
/// it as the narrator reaches the word (sad → happy at «قررت» / "decided").
///
/// Every cue word is one that the page's recording actually says, in Arabic
/// or English (a `=` word matches exactly, with no endings) — and every
/// `faceCue` is said in both, so a turn never depends on the language
/// (story_scene_cues_test.dart pins both against the real manifests).
